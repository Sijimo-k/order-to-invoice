// Writes demo/orders.json: fictional orders in the Shopify Admin REST shape.
// Totals are computed here in cents so the demo always adds up. Run: node tools/make-demo-orders.mjs
import { writeFileSync } from "node:fs";

const products = {
  sencha: { sku: "TEA-SEN-50", title: "Morning Sencha", variant: "50 g", price: 1250 },
  earl: { sku: "TEA-EGR-100", title: "Harbor Earl Grey", variant: "100 g", price: 980 },
  hojicha: { sku: "TEA-HOJ-80", title: "Roasted Hojicha", variant: "80 g", price: 1100 },
  oolong: { sku: "TEA-OOL-50", title: "High Mountain Oolong", variant: "50 g", price: 1530 },
  chai: { sku: "TEA-CHA-100", title: "Spiced Chai Blend", variant: "100 g", price: 1040 },
  sampler: { sku: "TEA-SMP-5", title: "Tasting Sampler", variant: "5 x 10 g", price: 1600 },
  kettle: { sku: "WARE-KTL-1", title: "Glass Kettle", variant: null, price: 3400 },
};

// [order no., date, first, last, city, state, zip, items, discount cents, cancelled]
const rows = [
  [1001, "2026-10-04T09:12:00-07:00", "Maya", "Lin", "Portland", "OR", "97201", [["sencha", 2], ["oolong", 1]], 0, false],
  [1002, "2026-10-11T14:40:00-07:00", "Daniel", "Okafor", "Austin", "TX", "73301", [["kettle", 1], ["earl", 2]], 500, false],
  [1003, "2026-10-19T08:05:00-07:00", "Sofia", "Marquez", "Denver", "CO", "80202", [["sampler", 1]], 0, false],
  [1004, "2026-10-27T19:22:00-07:00", "Ethan", "Brooks", "Madison", "WI", "53703", [["chai", 3]], 0, true],
  [1005, "2026-11-01T11:30:00-07:00", "Priya", "Raman", "Seattle", "WA", "98101", [["hojicha", 2], ["sencha", 1], ["sampler", 1]], 1000, false],
  [1006, "2026-11-03T16:48:00-07:00", "Lucas", "Bennett", "Boston", "MA", "02108", [["earl", 1]], 0, false],
  [1007, "2026-11-05T10:02:00-07:00", "Hana", "Sato", "San Jose", "CA", "95113", [["oolong", 2], ["kettle", 1]], 0, false],
  [1008, "2026-11-06T13:15:00-07:00", "Grace", "Whitfield", "Raleigh", "NC", "27601", [["chai", 1], ["hojicha", 1]], 0, false],
  [1009, "2026-11-07T09:55:00-07:00", "Omar", "Haddad", "Chicago", "IL", "60601", [["sampler", 2]], 320, false],
  [1010, "2026-11-08T18:40:00-07:00", "Chloe", "Nguyen", "Phoenix", "AZ", "85004", [["sencha", 1], ["earl", 1], ["chai", 1]], 0, false],
];

const money = (c) => (c / 100).toFixed(2);
const orders = rows.map(([no, created, first, last, city, state, zip, items, discount, cancelled], i) => {
  const lines = items.map(([key, qty], j) => {
    const p = products[key];
    return { id: no * 10 + j, sku: p.sku, title: p.title, variant_title: p.variant, quantity: qty, price: money(p.price) };
  });
  const subtotal = items.reduce((s, [key, qty]) => s + products[key].price * qty, 0);
  const shipping = subtotal - discount >= 4000 ? 0 : 600; // free shipping over $40
  const tax = Math.round((subtotal - discount) * 0.08);
  const total = subtotal - discount + shipping + tax;
  const name = `${first} ${last}`;
  const email = `${first}.${last}`.toLowerCase() + "@example.com";
  return {
    id: 7000000 + no,
    name: `#${no}`,
    order_number: no,
    created_at: created,
    email,
    currency: "USD",
    financial_status: cancelled ? "voided" : "pending",
    cancelled_at: cancelled ? created.replace(/T.*/, "T21:00:00-07:00") : null,
    subtotal_price: money(subtotal - discount),
    total_discounts: money(discount),
    total_tax: money(tax),
    total_price: money(total),
    total_shipping_price_set: { shop_money: { amount: money(shipping), currency_code: "USD" } },
    customer: { id: 9000 + i, first_name: first, last_name: last, email },
    billing_address: { name, address1: `${100 + i * 7} Demo Street`, city, province_code: state, zip, country: "United States" },
    line_items: lines,
  };
});

writeFileSync(new URL("../demo/orders.json", import.meta.url), JSON.stringify({ orders }, null, 2) + "\n");
console.log(`Wrote ${orders.length} fictional orders.`);

// The same orders built into the script, so "Orders URL = demo" works with no network setup.
writeFileSync(
  new URL("../src/DemoData.js", import.meta.url),
  "// Generated by tools/make-demo-orders.mjs from demo/orders.json. Fictional data.\n" +
    "var DEMO_ORDERS = " + JSON.stringify(orders) + ";\n",
);
console.log("Wrote src/DemoData.js.");
